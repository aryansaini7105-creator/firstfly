export function getEstimatedDistanceAndHours(from: string, to: string): { distanceKm: number; durationHours: number } {
  if (from === to) return { distanceKm: 45, durationHours: 1.5 };
  
  if (CITY_DISTANCES[from]?.[to]) {
    const km = CITY_DISTANCES[from][to];
    const speed = km > 300 ? 55 : 45;
    return { distanceKm: km, durationHours: Number((km / speed).toFixed(1)) };
  }

  if (CITY_DISTANCES[to]?.[from]) {
    const km = CITY_DISTANCES[to][from];
    const speed = km > 300 ? 55 : 45;
    return { distanceKm: km, durationHours: Number((km / speed).toFixed(1)) };
  }

  // Realistic default estimate
  return { distanceKm: 275, durationHours: 5.5 };
}

